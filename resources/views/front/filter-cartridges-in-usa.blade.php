<script>
  let productCaptchaRendered = false;
  let productCaptchaId = null;

  $('#productinquirysubmit').on('click', function () {
    const form = $('#productinquiry')[0];

    if (form.checkValidity()) {
      if (!productCaptchaRendered || productCaptchaId === null) {
        $('#captcha-error').text('Captcha is not ready yet. Please wait a moment.');
        return;
      }

      const recaptchaResponse = grecaptcha.getResponse(productCaptchaId);
      $('#g-recaptcha-response-product').val(recaptchaResponse);

      if (recaptchaResponse.length === 0) {
        $('#captcha-error').text('Please verify the CAPTCHA.');
        return;
      }

      $('#captcha-error').text('');
      $('#productinquiry').submit();
    } else {
      // Clear previous error messages
      $('.error-messages').text('');

      // Show errors only for invalid fields
      $('#productinquiry').find('input, textarea').each(function () {
        if (!this.checkValidity()) {
          $(this).siblings('.error-messages').text('This field is required.');
        }
      });
    }
  });

  // Clear errors on input
  $('input, textarea').on('input', function () {
    $(this).siblings('.error-messages').text('');
  });

  // Render reCAPTCHA when modal is shown
  $('#inquiryModal').on('shown.bs.modal', function () {
    if (!productCaptchaRendered) {
      productCaptchaId = grecaptcha.render('captcha_productinquiry', {
        sitekey: '6Lcrw_4pAAAAAKFnbxxXtyUZUa12DlHursCRjuak',
        callback: function (response) {
          $('#g-recaptcha-response-product').val(response);
          $('#captcha-error').text('');
        },
        'expired-callback': function () {
          $('#g-recaptcha-response-product').val('');
          $('#captcha-error').text('reCAPTCHA expired. Please verify again.');
        }
      });
      productCaptchaRendered = true;
    }
  });

  function openModal(productName) {
    $('#product_name').val(productName);
    $('#inquiryModal').modal('show');
  }
</script>